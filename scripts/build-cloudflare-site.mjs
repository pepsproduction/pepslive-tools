import { cp, mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = resolve(repositoryRoot, 'dist');
const markerPath = resolve(repositoryRoot, '.peps-cloudflare-build');
const expectedOutput = resolve(repositoryRoot, 'dist');
const studioDirectory = resolve(repositoryRoot, 'prototypes/studio-v2');
const studioCli = resolve(studioDirectory, 'node_modules/vite/bin/vite.js');
const studioBuildDirectory = resolve(repositoryRoot, 'assets/studio-v2');
const studioBuildMarker = resolve(repositoryRoot, '.pepsproduction-experience-build');

if (outputDirectory !== expectedOutput || dirname(outputDirectory) !== repositoryRoot) {
  throw new Error('Refusing to write outside the expected Cloudflare output directory.');
}
if (studioBuildDirectory !== resolve(repositoryRoot, 'assets', 'studio-v2')) {
  throw new Error('Refusing to write outside the expected experience asset directory.');
}

let outputExists = false;
try {
  outputExists = (await stat(outputDirectory)).isDirectory();
} catch { /* The first build has no output directory. */ }

if (outputExists) {
  try {
    await stat(markerPath);
  } catch {
    throw new Error('dist already exists and is not marked as this script\'s build output; move it before rebuilding.');
  }
  await rm(outputDirectory, { recursive: true });
}

let studioOutputExists = false;
try {
  studioOutputExists = (await stat(studioBuildDirectory)).isDirectory();
} catch { /* The integration bundle has not been built yet. */ }

if (studioOutputExists) {
  try {
    await stat(studioBuildMarker);
  } catch {
    throw new Error('assets/studio-v2 exists without this build script marker; move it before rebuilding.');
  }
}

try {
  await stat(studioCli);
} catch {
  throw new Error('Install the studio build dependencies first: npm ci --prefix prototypes/studio-v2');
}

const studioBuild = spawnSync(process.execPath, [studioCli, 'build', '--config', 'vite.production.config.js'], {
  cwd: studioDirectory,
  stdio: 'inherit'
});
if (studioBuild.error) throw studioBuild.error;
if (studioBuild.status !== 0) throw new Error(`Studio experience build failed (exit ${studioBuild.status ?? 'unknown'}).`);
await writeFile(studioBuildMarker, 'Generated by scripts/build-cloudflare-site.mjs\n', 'utf8');

await mkdir(outputDirectory, { recursive: true });

const publicFiles = [
  'index.html',
  '404.html',
  'start.html',
  'dock-ui.html',
  'equipment.html',
  'support.html',
  'follow.html',
  'admin.html',
  'dashboard.html',
  'admin/analytics/index.html',
  'data.json',
  'site-content.json'
];

for (const relativePath of publicFiles) {
  const destination = join(outputDirectory, relativePath);
  await mkdir(dirname(destination), { recursive: true });
  await cp(join(repositoryRoot, relativePath), destination);
}

await cp(join(repositoryRoot, 'assets'), join(outputDirectory, 'assets'), { recursive: true });
await writeFile(markerPath, 'Generated by scripts/build-cloudflare-site.mjs\n', 'utf8');

console.log(`Prepared ${publicFiles.length} public pages/data files and assets in ${outputDirectory}`);
